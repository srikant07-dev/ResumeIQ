import { createClient } from '@supabase/supabase-js';

const supabaseUrl = import.meta.env.VITE_SUPABASE_URL || 'https://placeholder.supabase.co';
const supabaseAnonKey = import.meta.env.VITE_SUPABASE_ANON_KEY || 'placeholder-anon-key';

if (import.meta.env.PROD && (supabaseUrl.includes('placeholder') || supabaseAnonKey.includes('placeholder'))) {
  console.error('[ResumeIQ Security Warning] Production build is running with placeholder Supabase credentials. Authentication requests will fail.');
}

export const supabase = createClient(supabaseUrl, supabaseAnonKey, {
  auth: {
    persistSession: true,
    autoRefreshToken: true,
    detectSessionInUrl: true,
  },
});
